"""YouTube videos: resolve a link into a SourceInfo. youtube_formats picks what to download.

yt-dlp runs YouTube's scripts on Deno, whose path is always passed in. A Topic upload, whose
description YouTube writes itself, brings YouTube Music's track, artists, album and year, which the
suggestion uses as SoundCloud's publisher fields are used (TECH_SPEC §7 and §8).
"""

from __future__ import annotations

import logging
import re
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from datetime import date, datetime
from pathlib import Path
from typing import TYPE_CHECKING, Any

from scmp3.core import cover_sources, engine
from scmp3.core.errors import ErrorKind, ScmpError
from scmp3.core.models import FormatOption, SourceInfo
from scmp3.core.sources import ytdlp_errors
from scmp3.core.sources.soundcloud import ResolvedTrack
from scmp3.core.urls import classify_link

if TYPE_CHECKING:
    from yt_dlp import YoutubeDL

# How YouTube ends the description of a Topic upload.
TOPIC_FOOTER = "Auto-generated by YouTube."
# The release date labels put in the descriptions of the tracks they deliver, Topic or not.
_RELEASED_ON = re.compile(r"^Released on: (\d{4})-(\d{2})-(\d{2})\s*$", re.MULTILINE)
# A stream still running or about to start has no recording to save yet.
LIVE_STATUSES = frozenset({"is_live", "is_upcoming", "post_live"})
# Codec names for the start of yt-dlp's acodec, such as mp4a.40.2.
CODECS = {"mp4a": "aac", "opus": "opus"}
# yt-dlp ranks a format it suspects is damaged at -10.
DAMAGED = -10

log = logging.getLogger(__name__)


@dataclass(frozen=True)
class MusicFields:
    """What YouTube Music says about a Topic upload."""

    track: str
    artists: list[str]
    album: str | None
    released: date | None


def make_ydl(
    deno: Path,
    *,
    progress_hook: engine.ProgressHook | None = None,
    extra: Mapping[str, Any] | None = None,
) -> YoutubeDL:
    """engine.make_ydl, with yt-dlp told where Deno is. Keys in `extra` override both."""
    options = {**ydl_options(deno), **(extra or {})}
    return engine.make_ydl(progress_hook=progress_hook, extra=options)


def ydl_options(deno: Path) -> dict[str, Any]:
    """The options YouTube adds to the standard ones, new each time so none are shared.

    engine.make_ydl adds remote_components itself when yt-dlp-ejs doesn't match yt-dlp.
    """
    return {"js_runtimes": {"deno": {"path": str(deno)}}}


def resolve_track(url: str, ydl: YoutubeDL, token: str | None = None) -> ResolvedTrack:
    """Resolve a video link, raising ScmpError when YouTube won't give the video.

    Build `ydl` with make_ydl. `token` is a SoundCloud sign-in, so YouTube ignores it.
    """
    yt_dlp = engine.load_yt_dlp()
    link = _video_link(url)
    try:
        info = ydl.extract_info(link, download=False)
    except yt_dlp.utils.YoutubeDLError as error:
        raise _youtube_refusal(error) from error
    status = info.get("live_status")
    if status in LIVE_STATUSES:
        detail = f"the video's live status is {status}"
        raise ScmpError(ErrorKind.unavailable, detail, reason="live_stream")
    return ResolvedTrack(source_from_info(link, info), info)


def _youtube_refusal(error: BaseException) -> ScmpError:
    """yt-dlp's error as a ScmpError. An unavailable video with no other reason was removed.

    That covers a 404 or 410, whose text would otherwise be SoundCloud's.
    """
    refusal = ytdlp_errors.to_scmp_error(error)
    if refusal.kind == ErrorKind.unavailable and refusal.reason is None:
        refusal.reason = "removed"
    return refusal


def _video_link(url: str) -> str:
    """The normalized form of a video link, before any request is made."""
    kind, link = classify_link(url)
    if kind != "youtube_video":
        raise ValueError(f"resolve takes a YouTube video link, not a {kind} link")
    return link


def source_from_info(link: str, info: Mapping[str, Any]) -> SourceInfo:
    """The SourceInfo for a video, from yt-dlp's info dict."""
    music = music_fields(info)
    upload_date = _yyyymmdd(info.get("upload_date"))
    description = info.get("description") or None
    released = (
        (music.released if music else None)
        or _yyyymmdd(info.get("release_date"))
        or _released_on(description)
    )
    return SourceInfo(
        kind="youtube",
        id=f"youtube:{info['id']}",
        url=link,
        title=music.track if music else info.get("title") or "",
        uploader=info.get("uploader") or info.get("channel") or "",
        artists=music.artists if music else [],
        album=music.album if music else None,
        release_date=released or upload_date,
        upload_date=upload_date,
        description=description,
        duration=info.get("duration"),
        artwork_url=artwork_url(str(info["id"]), info.get("thumbnails") or []),
        formats=audio_formats(info.get("formats") or []),
    )


def music_fields(info: Mapping[str, Any]) -> MusicFields | None:
    """YouTube Music's fields, which yt-dlp reads from a Topic upload's description."""
    description = (info.get("description") or "").strip()
    if not description.endswith(TOPIC_FOOTER):
        return None
    track = (info.get("track") or "").strip()
    artists = [name.strip() for name in info.get("artists") or [] if name and name.strip()]
    if not track or not artists:
        return None
    return MusicFields(track, artists, info.get("album") or None, _released(info))


def _released(info: Mapping[str, Any]) -> date | None:
    """A Topic upload's release date, or its year from the ℗ line."""
    released = _yyyymmdd(info.get("release_date"))
    if released is not None:
        return released
    year = info.get("release_year")
    if not isinstance(year, int) or not 1 <= year <= 9999:
        return None
    # Only the year goes in the tags, so the first of January stands in for the day.
    return date(year, 1, 1)


def _released_on(description: str | None) -> date | None:
    """The date on a "Released on:" line, as labels write it, or None."""
    found = _RELEASED_ON.search(description or "")
    if found is None:
        return None
    try:
        return date(int(found[1]), int(found[2]), int(found[3]))
    except ValueError:
        log.warning("Ignoring a release date that isn't a date: %s", found[0].strip())
        return None


def artwork_url(video_id: str, thumbnails: Sequence[Mapping[str, Any]]) -> str | None:
    """The largest of YouTube's usual sizes that yt-dlp lists, or else its own pick.

    yt-dlp lists sizes without checking them, so the cover tries the smaller ones after it.
    """
    listed = " ".join(str(thumbnail.get("url") or "") for thumbnail in thumbnails)
    for size in cover_sources.YOUTUBE_SIZES:
        if f"/{size}." in listed:
            return cover_sources.youtube_thumbnail(video_id, size)
    return cover_sources.pick_largest(thumbnails)


def audio_formats(formats: Sequence[Mapping[str, Any]]) -> list[FormatOption]:
    """The audio-only streams of the video's main audio track, as FormatOptions.

    Dubbed tracks, compressed DRC copies, DRM streams and streams yt-dlp thinks are damaged are
    left out.
    """
    usable = [fmt for fmt in formats if _is_plain_audio(fmt)]
    if not usable:
        return []
    main_track = max(_language_rank(fmt) for fmt in usable)
    return [_format_option(fmt) for fmt in usable if _language_rank(fmt) == main_track]


def _is_plain_audio(fmt: Mapping[str, Any]) -> bool:
    if fmt.get("vcodec") != "none" or (fmt.get("acodec") or "none") == "none":
        return False
    if fmt.get("has_drm") or fmt.get("preference") == DAMAGED:
        return False
    return not str(fmt.get("format_id") or "").endswith("drc")


def _language_rank(fmt: Mapping[str, Any]) -> int:
    """yt-dlp's rank for the audio track: highest for the original, lower for dubs."""
    rank = fmt.get("language_preference")
    return rank if isinstance(rank, int) else -1


def _format_option(fmt: Mapping[str, Any]) -> FormatOption:
    acodec = str(fmt.get("acodec"))
    prefix = acodec.split(".", 1)[0].lower()
    return FormatOption(
        format_id=str(fmt.get("format_id") or ""),
        ext=fmt.get("ext") or "",
        codec=CODECS.get(prefix, prefix),
        bitrate=fmt.get("abr") or fmt.get("tbr"),
    )


def _yyyymmdd(value: str | None) -> date | None:
    """A date from yt-dlp's YYYYMMDD form."""
    if not value:
        return None
    try:
        return datetime.strptime(value, "%Y%m%d").date()
    except ValueError:
        log.warning("Ignoring a date yt-dlp gave in an unexpected form: %r", value)
        return None
