@pytest.mark.parametrize(
    "unwanted",
    [
        {"format_id": "251-drc"},
        {"has_drm": True},
        {"preference": -10},
        {"vcodec": "vp9"},
        {"acodec": "none"},
    ],
    ids=["compressed copy", "drm", "damaged", "video", "storyboard"],
)
def test_streams_that_wouldnt_save_well_are_left_out(unwanted: dict[str, Any]) -> None:
    plain = {"format_id": "251", "ext": "webm", "acodec": "opus", "vcodec": "none", "abr": 140}
    assert [fmt.format_id for fmt in youtube.audio_formats([plain])] == ["251"]
    assert youtube.audio_formats([{**plain, **unwanted}]) == []


