def test_resolving_extracts_the_normalized_link() -> None:
    info = recorder.load("topic_upload")
    ydl = ReplayYdl(info)
    resolved = youtube.resolve_track("https://youtu.be/y9qO_xgE34Q?si=shared", ydl)  # type: ignore[arg-type]
    assert ydl.extracted == [link("y9qO_xgE34Q")]
    assert resolved.info is info
    assert resolved.source.url == link("y9qO_xgE34Q")


def test_youtubes_refusal_comes_out_as_a_scmp_error() -> None:
    inner = ExtractorError("[youtube] x: Video unavailable", expected=True)
    ydl = ReplayYdl(error=DownloadError(f"ERROR: {inner}", exc_info=(type(inner), inner, None)))
    with pytest.raises(ScmpError) as error:
        youtube.resolve_track(link("y9qO_xgE34Q"), ydl)  # type: ignore[arg-type]
    assert (error.value.kind, error.value.reason) == (ErrorKind.unavailable, "removed")


def test_a_video_youtube_answers_404_for_counts_as_removed() -> None:
    inner = HTTPError(Response(io.BytesIO(b""), link("y9qO_xgE34Q"), {}, status=404))
    error = DownloadError("ERROR: HTTP Error 404: Not Found", exc_info=(type(inner), inner, None))
    with pytest.raises(ScmpError) as raised:
        youtube.resolve_track(link("y9qO_xgE34Q"), ReplayYdl(error=error))  # type: ignore[arg-type]
    assert (raised.value.kind, raised.value.reason) == (ErrorKind.unavailable, "removed")


