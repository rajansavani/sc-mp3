def load_recorder() -> ModuleType:
    """tests/fixtures/record_youtube.py, which pytest's importlib mode can't import by name."""
    name = "scmp3_test_fixture_record_youtube"
    if name not in sys.modules:
        path = Path(__file__).parents[1] / "fixtures" / "record_youtube.py"
        spec = importlib.util.spec_from_file_location(name, path)
        assert spec is not None and spec.loader is not None
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        sys.modules[name] = module
    return sys.modules[name]


recorder = load_recorder()


def link(video_id: str) -> str:
    return f"https://www.youtube.com/watch?v={video_id}"


class ReplayYdl:
    """Stands in for a YoutubeDL, answering with one info dict or raising one error."""

    def __init__(self, info: dict[str, Any] | None = None, error: Exception | None = None) -> None:
        self.info = info
        self.error = error
        self.extracted: list[str] = []

    def extract_info(self, url: str, download: bool = True) -> dict[str, Any]:
        self.extracted.append(url)
        if self.error is not None:
            raise self.error
        assert self.info is not None
        return self.info


def test_a_topic_upload_takes_youtube_musics_track_artists_album_and_date() -> None:
    info = recorder.load("topic_upload")
    source = youtube.source_from_info(link(info["id"]), info)
    assert source.kind == "youtube"
    assert source.id == "youtube:y9qO_xgE34Q"
    assert source.title == "WAIT FOR U"
    assert source.uploader == "Future"
    assert source.artists == ["Future", "Drake", "Tems"]
    assert source.album == "I NEVER LIKED YOU"
    assert source.release_date == date(2022, 4, 29)
    assert source.description and source.description.endswith("Auto-generated by YouTube.")


