def test_the_youtube_dl_runs_on_the_deno_it_is_given(tmp_path: Path) -> None:
    deno = tmp_path / "deno.exe"
    with youtube.make_ydl(deno, extra={"socket_timeout": 5}) as ydl:
        assert ydl.params["js_runtimes"] == {"deno": {"path": str(deno)}}
        assert ydl.params["socket_timeout"] == 5


def test_each_youtube_dl_gets_its_own_options() -> None:
    first, second = youtube.ydl_options(Path("a")), youtube.ydl_options(Path("a"))
    first["js_runtimes"]["deno"]["path"] = "changed"
    assert second["js_runtimes"]["deno"]["path"] == "a"


