def test_only_the_audio_streams_are_listed_with_plain_codec_names() -> None:
    info = recorder.load("official_audio")
    formats = youtube.audio_formats(info["formats"])
    assert [(fmt.format_id, fmt.ext, fmt.codec) for fmt in formats] == [
        ("139", "m4a", "aac"),
        ("249", "webm", "opus"),
        ("250", "webm", "opus"),
        ("140", "m4a", "aac"),
        ("251", "webm", "opus"),
    ]
    assert formats[-1].bitrate == pytest.approx(142.6)


